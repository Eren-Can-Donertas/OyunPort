-- OyunPort  V1: Çekirdek şema (ara rapor §4 ve §5)
-- 18 tablo; PK/FK/UNIQUE/CHECK kısıtları ve FK destek indeksleri.
-- FK davranışları rapor §5 tablosuna göre:
--   * APP_USER, PRODUCT, STORE_ORDER, ORDER_ITEM, PAYMENT_ATTEMPT, LIBRARY_ENTRY
--     bağlantıları ON DELETE RESTRICT (tarihsel veri silinmez).
--   * USER_ROLE ve WISHLIST user/product FK'leri CASCADE; PRODUCT_GENRE ve
--     PRODUCT_DEVELOPER product FK'leri CASCADE; genre/developer FK'leri RESTRICT.
--   * Diğer bütün FK'ler RESTRICT; bütün yapay ID güncellemeleri ON UPDATE RESTRICT.
-- Tablolar arası kurallar (BR01, BR04, BR05, BR06, BR08, BR09) V2'deki trigger'larda.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 4.1 Hesap tabloları
-- ---------------------------------------------------------------------
CREATE TABLE app_user (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email          VARCHAR(254) NOT NULL,
    display_name   VARCHAR(60)  NOT NULL,
    password_hash  VARCHAR(100) NOT NULL,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_app_user PRIMARY KEY (user_id),
    CONSTRAINT uq_app_user_email UNIQUE (email),
    CONSTRAINT ck_app_user_email CHECK (email = lower(email) AND email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
    CONSTRAINT ck_app_user_display_name CHECK (char_length(btrim(display_name)) BETWEEN 2 AND 60),
    CONSTRAINT ck_app_user_password_hash CHECK (char_length(password_hash) >= 20)
);

CREATE TABLE app_role (
    role_id    INTEGER GENERATED BY DEFAULT AS IDENTITY,
    role_name  VARCHAR(20) NOT NULL,
    CONSTRAINT pk_app_role PRIMARY KEY (role_id),
    CONSTRAINT uq_app_role_name UNIQUE (role_name),
    CONSTRAINT ck_app_role_name CHECK (role_name IN ('CUSTOMER', 'ADMIN'))
);

CREATE TABLE user_role (
    user_id  BIGINT  NOT NULL,
    role_id  INTEGER NOT NULL,
    CONSTRAINT pk_user_role PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_role_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_user_role_role FOREIGN KEY (role_id) REFERENCES app_role (role_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX ix_user_role_role ON user_role (role_id);

-- ---------------------------------------------------------------------
-- 4.1 Katalog tabloları
-- ---------------------------------------------------------------------
CREATE TABLE publisher (
    publisher_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(120) NOT NULL,
    country       VARCHAR(60),
    CONSTRAINT pk_publisher PRIMARY KEY (publisher_id),
    CONSTRAINT ck_publisher_name CHECK (char_length(btrim(name)) > 0)
);

CREATE TABLE developer (
    developer_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(120) NOT NULL,
    country       VARCHAR(60),
    CONSTRAINT pk_developer PRIMARY KEY (developer_id),
    CONSTRAINT ck_developer_name CHECK (char_length(btrim(name)) > 0)
);

CREATE TABLE genre (
    genre_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name      VARCHAR(60) NOT NULL,
    CONSTRAINT pk_genre PRIMARY KEY (genre_id),
    CONSTRAINT uq_genre_name UNIQUE (name),
    CONSTRAINT ck_genre_name CHECK (char_length(btrim(name)) > 0)
);

-- PRODUCT superclass. Raporda belirtildiği gibi product_type sütunu YOKTUR;
-- alt tür BASE_GAME/DLC üyeliğinden türetilir (BR01, V2 trigger'ları).
CREATE TABLE product (
    product_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    publisher_id  BIGINT        NOT NULL,
    title         VARCHAR(150)  NOT NULL,
    description   TEXT,
    list_price    NUMERIC(12,2) NOT NULL,
    release_date  DATE          NOT NULL,
    is_active     BOOLEAN       NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_product PRIMARY KEY (product_id),
    CONSTRAINT fk_product_publisher FOREIGN KEY (publisher_id) REFERENCES publisher (publisher_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_product_title CHECK (char_length(btrim(title)) > 0),
    CONSTRAINT ck_product_list_price CHECK (list_price >= 0)
);
-- product(publisher_id, ...) indeksi V4'te performans deneyi adayı olarak oluşturulur.

CREATE TABLE base_game (
    product_id            BIGINT NOT NULL,
    minimum_requirements  TEXT   NOT NULL,
    CONSTRAINT pk_base_game PRIMARY KEY (product_id),
    CONSTRAINT fk_base_game_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_base_game_requirements CHECK (char_length(btrim(minimum_requirements)) > 0)
);

CREATE TABLE dlc (
    product_id       BIGINT NOT NULL,
    base_game_id     BIGINT NOT NULL,
    content_summary  TEXT   NOT NULL,
    CONSTRAINT pk_dlc PRIMARY KEY (product_id),
    CONSTRAINT fk_dlc_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    -- BR05: DLC base_game_id yalnızca BASE_GAME tablosuna bağlanır.
    CONSTRAINT fk_dlc_base_game FOREIGN KEY (base_game_id) REFERENCES base_game (product_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_dlc_not_self CHECK (base_game_id <> product_id),
    CONSTRAINT ck_dlc_summary CHECK (char_length(btrim(content_summary)) > 0)
);
CREATE INDEX ix_dlc_base_game ON dlc (base_game_id);

CREATE TABLE product_genre (
    product_id  BIGINT NOT NULL,
    genre_id    BIGINT NOT NULL,
    CONSTRAINT pk_product_genre PRIMARY KEY (product_id, genre_id),
    CONSTRAINT fk_product_genre_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_product_genre_genre FOREIGN KEY (genre_id) REFERENCES genre (genre_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX ix_product_genre_genre ON product_genre (genre_id, product_id);

CREATE TABLE product_developer (
    product_id    BIGINT NOT NULL,
    developer_id  BIGINT NOT NULL,
    CONSTRAINT pk_product_developer PRIMARY KEY (product_id, developer_id),
    CONSTRAINT fk_product_developer_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_product_developer_developer FOREIGN KEY (developer_id) REFERENCES developer (developer_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX ix_product_developer_developer ON product_developer (developer_id, product_id);

CREATE TABLE wishlist (
    user_id     BIGINT      NOT NULL,
    product_id  BIGINT      NOT NULL,
    added_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_wishlist PRIMARY KEY (user_id, product_id),
    CONSTRAINT fk_wishlist_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
        ON DELETE CASCADE ON UPDATE RESTRICT,
    CONSTRAINT fk_wishlist_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE CASCADE ON UPDATE RESTRICT
);
CREATE INDEX ix_wishlist_product ON wishlist (product_id);

-- ---------------------------------------------------------------------
-- 4.3 İşlem ve kullanıcı etkinliği tabloları
-- ---------------------------------------------------------------------
CREATE TABLE store_order (
    order_id      BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT      NOT NULL,
    status        VARCHAR(10) NOT NULL DEFAULT 'PENDING',
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at  TIMESTAMPTZ,
    checkout_key  UUID        NOT NULL,
    CONSTRAINT pk_store_order PRIMARY KEY (order_id),
    CONSTRAINT fk_store_order_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT uq_store_order_checkout_key UNIQUE (checkout_key),
    CONSTRAINT ck_store_order_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_store_order_completed_at CHECK ((status = 'COMPLETED') = (completed_at IS NOT NULL)),
    CONSTRAINT ck_store_order_completed_after_created CHECK (completed_at IS NULL OR completed_at >= created_at)
);
-- store_order(user_id, created_at DESC) ve tamamlanmış satış kısmi indeksi V4'te.

-- ORDER_ITEM: STORE_ORDER'a bağlı weak entity; line_no partial key (rapor §4.4 DDL).
CREATE TABLE order_item (
    order_id         BIGINT        NOT NULL,
    line_no          INTEGER       NOT NULL,
    product_id       BIGINT        NOT NULL,
    unit_price_paid  NUMERIC(12,2) NOT NULL,
    CONSTRAINT pk_order_item PRIMARY KEY (order_id, line_no),
    CONSTRAINT uq_order_item_order_product UNIQUE (order_id, product_id),      -- BR03
    CONSTRAINT fk_order_item_order FOREIGN KEY (order_id) REFERENCES store_order (order_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_order_item_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_order_item_line_no CHECK (line_no > 0),
    CONSTRAINT ck_order_item_price CHECK (unit_price_paid >= 0)
);
-- order_item(product_id, order_id) V4'te.

CREATE TABLE payment_attempt (
    payment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    order_id      BIGINT        NOT NULL,
    amount        NUMERIC(12,2) NOT NULL,
    status        VARCHAR(10)   NOT NULL,
    attempted_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    request_key   UUID          NOT NULL,
    CONSTRAINT pk_payment_attempt PRIMARY KEY (payment_id),
    CONSTRAINT fk_payment_attempt_order FOREIGN KEY (order_id) REFERENCES store_order (order_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT uq_payment_attempt_request_key UNIQUE (request_key),           -- idempotency
    CONSTRAINT ck_payment_attempt_amount CHECK (amount >= 0),
    CONSTRAINT ck_payment_attempt_status CHECK (status IN ('SUCCESS', 'FAILED'))
);
CREATE INDEX ix_payment_attempt_order ON payment_attempt (order_id, attempted_at);
-- BR09: sipariş başına en fazla bir SUCCESS (rapor §4.4).
CREATE UNIQUE INDEX uq_one_successful_payment ON payment_attempt (order_id) WHERE status = 'SUCCESS';

CREATE TABLE library_entry (
    library_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT      NOT NULL,
    product_id   BIGINT      NOT NULL,
    order_id     BIGINT      NOT NULL,
    line_no      INTEGER     NOT NULL,
    acquired_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_library_entry PRIMARY KEY (library_id),
    CONSTRAINT uq_library_entry_user_product UNIQUE (user_id, product_id),     -- BR02
    CONSTRAINT uq_library_entry_source_item UNIQUE (order_id, line_no),        -- SOURCES 0..1:1
    CONSTRAINT fk_library_entry_user FOREIGN KEY (user_id) REFERENCES app_user (user_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_library_entry_product FOREIGN KEY (product_id) REFERENCES product (product_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_library_entry_source_item FOREIGN KEY (order_id, line_no) REFERENCES order_item (order_id, line_no)
        ON DELETE RESTRICT ON UPDATE RESTRICT
);
CREATE INDEX ix_library_entry_product ON library_entry (product_id);

CREATE TABLE play_session (
    session_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    library_id  BIGINT      NOT NULL,
    started_at  TIMESTAMPTZ NOT NULL,
    ended_at    TIMESTAMPTZ,
    CONSTRAINT pk_play_session PRIMARY KEY (session_id),
    CONSTRAINT fk_play_session_library FOREIGN KEY (library_id) REFERENCES library_entry (library_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_play_session_interval CHECK (ended_at IS NULL OR ended_at >= started_at)
);
-- Destekleyici kısıt (Ç9): bir kütüphane kaydında aynı anda en fazla bir açık oturum.
CREATE UNIQUE INDEX uq_play_session_one_open ON play_session (library_id) WHERE ended_at IS NULL;
-- play_session(library_id, started_at) V4'te.

-- REVIEW: APP_USER–BASE_GAME M:N ilişki entity'si; sahiplik FK ile zorunlu (BR06).
CREATE TABLE review (
    user_id       BIGINT      NOT NULL,
    base_game_id  BIGINT      NOT NULL,
    rating        SMALLINT    NOT NULL,
    comment       VARCHAR(2000),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_review PRIMARY KEY (user_id, base_game_id),
    CONSTRAINT fk_review_ownership FOREIGN KEY (user_id, base_game_id)
        REFERENCES library_entry (user_id, product_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT fk_review_base_game FOREIGN KEY (base_game_id) REFERENCES base_game (product_id)
        ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_review_updated CHECK (updated_at >= created_at)
);
CREATE INDEX ix_review_base_game ON review (base_game_id);

COMMENT ON TABLE product IS 'PRODUCT superclass; total+disjoint specialization BASE_GAME/DLC (BR01)';
COMMENT ON TABLE order_item IS 'Weak entity; PK=(order_id, line_no), CONTAINS identifying relationship';
COMMENT ON COLUMN order_item.unit_price_paid IS 'Satın alma anındaki net fiyat (BR07); product.list_price değildir';
COMMENT ON TABLE library_entry IS 'OWNS ilişkisi; (user_id, product_id) ve (order_id, line_no) aday anahtarlar';
